CREATE TABLE edu_graph_ingestion_job (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    source_file_id BIGINT NOT NULL,
    course_id BIGINT NULL,
    title VARCHAR(500) NOT NULL,
    source_type VARCHAR(30) NOT NULL,
    copyright_status VARCHAR(30) NOT NULL,
    created_by BIGINT NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    status VARCHAR(40) NOT NULL DEFAULT 'CREATED',
    progress_percent INT NOT NULL DEFAULT 0,
    base_graph_version VARCHAR(100) NULL,
    ingestion_batch_id VARCHAR(64) NULL,
    batch_revision BIGINT NULL,
    total_candidate_count INT NOT NULL DEFAULT 0,
    node_count INT NOT NULL DEFAULT 0,
    edge_count INT NOT NULL DEFAULT 0,
    source_count INT NOT NULL DEFAULT 0,
    pending_candidate_count INT NOT NULL DEFAULT 0,
    accepted_candidate_count INT NOT NULL DEFAULT 0,
    rejected_candidate_count INT NOT NULL DEFAULT 0,
    error_count INT NOT NULL DEFAULT 0,
    warning_count INT NOT NULL DEFAULT 0,
    extractor_model_provider VARCHAR(40) NULL,
    extractor_model_version VARCHAR(100) NULL,
    extractor_prompt_version VARCHAR(100) NULL,
    extractor_prompt_sha256 CHAR(64) NULL,
    reviewer_model_provider VARCHAR(40) NULL,
    reviewer_model_version VARCHAR(100) NULL,
    reviewer_prompt_version VARCHAR(100) NULL,
    reviewer_prompt_sha256 CHAR(64) NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 3,
    error_code VARCHAR(80) NULL,
    error_message VARCHAR(1000) NULL,
    published_graph_version VARCHAR(100) NULL,
    previous_graph_version VARCHAR(100) NULL,
    release_sha256 CHAR(64) NULL,
    version_no BIGINT NOT NULL DEFAULT 1,
    started_at DATETIME(3) NULL,
    finished_at DATETIME(3) NULL,
    published_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_graph_ingestion_file FOREIGN KEY (source_file_id) REFERENCES edu_file_object (id),
    CONSTRAINT fk_graph_ingestion_course FOREIGN KEY (course_id) REFERENCES edu_course (id),
    CONSTRAINT fk_graph_ingestion_creator FOREIGN KEY (created_by) REFERENCES edu_user (id),
    CONSTRAINT uk_graph_ingestion_request UNIQUE (request_id),
    CONSTRAINT uk_graph_ingestion_idempotency UNIQUE (created_by, idempotency_key),
    KEY idx_graph_ingestion_status_time (status, updated_at),
    KEY idx_graph_ingestion_file (source_file_id),
    KEY idx_graph_ingestion_batch (ingestion_batch_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE edu_graph_review_action (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    job_id BIGINT NOT NULL,
    reviewer_id BIGINT NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    expected_revision BIGINT NOT NULL,
    resulting_revision BIGINT NULL,
    decision_count INT NOT NULL,
    decisions_json JSON NOT NULL,
    response_json JSON NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    CONSTRAINT fk_graph_review_job FOREIGN KEY (job_id) REFERENCES edu_graph_ingestion_job (id),
    CONSTRAINT fk_graph_review_user FOREIGN KEY (reviewer_id) REFERENCES edu_user (id),
    CONSTRAINT uk_graph_review_idempotency UNIQUE (reviewer_id, idempotency_key),
    CONSTRAINT uk_graph_review_request UNIQUE (request_id),
    KEY idx_graph_review_job_time (job_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE edu_graph_ingestion_outbox (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    job_id BIGINT NOT NULL,
    idempotency_record_id BIGINT NULL,
    event_type VARCHAR(40) NOT NULL,
    dedupe_key VARCHAR(190) NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    payload_json JSON NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    attempt_count INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 3,
    next_attempt_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    lease_owner VARCHAR(100) NULL,
    lease_until DATETIME(3) NULL,
    last_error_code VARCHAR(80) NULL,
    last_error_message VARCHAR(1000) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    completed_at DATETIME(3) NULL,
    CONSTRAINT fk_graph_ingestion_outbox_job FOREIGN KEY (job_id) REFERENCES edu_graph_ingestion_job (id),
    CONSTRAINT fk_graph_ingestion_outbox_idempotency FOREIGN KEY (idempotency_record_id)
        REFERENCES edu_idempotency_record (id) ON DELETE SET NULL,
    CONSTRAINT uk_graph_ingestion_outbox_dedupe UNIQUE (dedupe_key),
    KEY idx_graph_ingestion_outbox_claim (status, next_attempt_at, lease_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

